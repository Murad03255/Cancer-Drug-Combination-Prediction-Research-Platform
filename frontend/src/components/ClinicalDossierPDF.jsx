import React, { useState, useRef } from 'react';
import {
  FaFilePdf,
  FaDownload,
  FaCheckCircle,
  FaDna,
  FaBrain,
  FaFlask,
  FaShieldAlt,
  FaSpinner,
  FaHospital,
  FaFileAlt,
  FaStamp,
} from 'react-icons/fa';
import jsPDF from 'jspdf';
import toast from 'react-hot-toast';

/**
 * ClinicalDossierPDF — One-Click Clinical Dossier PDF Export
 * Generates a professional multi-page clinical research dossier from prediction results.
 */
export default function ClinicalDossierPDF({ result, molecularData }) {
  const [generating, setGenerating] = useState(false);
  const [generated, setGenerated] = useState(false);

  if (!result) return null;

  const generatePDF = async () => {
    setGenerating(true);
    toast.loading('Generating clinical dossier...', { id: 'pdf-gen' });

    try {
      const doc = new jsPDF({
        orientation: 'portrait',
        unit: 'mm',
        format: 'a4',
      });

      const pageWidth = doc.internal.pageSize.getWidth();
      const pageHeight = doc.internal.pageSize.getHeight();
      const margin = 18;
      const contentWidth = pageWidth - margin * 2;
      let y = margin;

      // Color palette
      const colors = {
        darkBg: [15, 23, 42],
        cardBg: [30, 41, 59],
        primary: [20, 184, 166],     // teal
        secondary: [99, 102, 241],   // indigo
        accent: [56, 189, 248],      // cyan
        danger: [244, 63, 94],       // rose
        warning: [245, 158, 11],     // amber
        text: [248, 250, 252],       // slate-50
        textMuted: [148, 163, 184],  // slate-400
        textDim: [100, 116, 139],    // slate-500
        border: [51, 65, 85],        // slate-700
      };

      // Helper: set text color from RGB array
      const setColor = (c) => doc.setTextColor(c[0], c[1], c[2]);
      const setFill = (c) => doc.setFillColor(c[0], c[1], c[2]);
      const setDraw = (c) => doc.setDrawColor(c[0], c[1], c[2]);

      // ====== PAGE BACKGROUND FILL ======
      const fillPageBg = () => {
        setFill(colors.darkBg);
        doc.rect(0, 0, pageWidth, pageHeight, 'F');
      };

      // ====== HEADER BAND ======
      const drawHeader = () => {
        // Top gradient-like band
        setFill(colors.primary);
        doc.rect(0, 0, pageWidth, 3, 'F');

        setFill([20, 184, 166]); // teal-500
        doc.roundedRect(margin, 8, contentWidth, 28, 3, 3, 'F');

        // Title
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(14);
        setColor([255, 255, 255]);
        doc.text('CANCER DRUG COMBINATION PLATFORM', margin + 6, 20);

        doc.setFontSize(8);
        doc.setFont('helvetica', 'normal');
        doc.text('Clinical Research Dossier — Drug Combination Synergy Analysis', margin + 6, 28);

        // Report ID & Date
        const reportId = `SYN-${Date.now().toString(36).toUpperCase()}`;
        doc.setFontSize(7);
        doc.text(`Report ID: ${reportId}`, pageWidth - margin - 6, 20, { align: 'right' });
        doc.text(new Date().toISOString().split('T')[0], pageWidth - margin - 6, 26, { align: 'right' });

        return 44;
      };

      // ====== FOOTER ======
      const drawFooter = (pageNum, totalPages) => {
        setDraw(colors.border);
        doc.setLineWidth(0.3);
        doc.line(margin, pageHeight - 14, pageWidth - margin, pageHeight - 14);

        doc.setFontSize(6);
        setColor(colors.textDim);
        doc.setFont('helvetica', 'italic');
        doc.text(
          'CONFIDENTIAL — For Research Use Only. Not for clinical decision-making. Generated by Cancer Drug Combination Prediction & Research Platform.',
          margin,
          pageHeight - 10
        );
        doc.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin, pageHeight - 10, { align: 'right' });
      };

      // ====== SECTION HEADER ======
      const drawSection = (title, icon, yPos) => {
        setFill(colors.cardBg);
        doc.roundedRect(margin, yPos, contentWidth, 9, 2, 2, 'F');
        setDraw(colors.border);
        doc.roundedRect(margin, yPos, contentWidth, 9, 2, 2, 'S');

        doc.setFontSize(9);
        doc.setFont('helvetica', 'bold');
        setColor(colors.primary);
        doc.text(`${icon}  ${title}`, margin + 4, yPos + 6.5);

        return yPos + 13;
      };

      // ====== DATA ROW ======
      const drawDataRow = (label, value, yPos, valueColor = colors.text) => {
        doc.setFontSize(7.5);
        doc.setFont('helvetica', 'normal');
        setColor(colors.textMuted);
        doc.text(label, margin + 4, yPos);
        doc.setFont('helvetica', 'bold');
        setColor(valueColor);
        doc.text(String(value), margin + 58, yPos);
        return yPos + 5.5;
      };

      // ====== KEY-VALUE CARD ======
      const drawCard = (xPos, yPos, width, height, label, value, valueColor = colors.primary) => {
        setFill(colors.cardBg);
        doc.roundedRect(xPos, yPos, width, height, 2, 2, 'F');
        setDraw(colors.border);
        doc.roundedRect(xPos, yPos, width, height, 2, 2, 'S');

        doc.setFontSize(6.5);
        doc.setFont('helvetica', 'normal');
        setColor(colors.textDim);
        doc.text(label, xPos + 3, yPos + 5);

        doc.setFontSize(14);
        doc.setFont('helvetica', 'bold');
        setColor(valueColor);
        doc.text(String(value), xPos + 3, yPos + 14);
      };

      // ====== SHAP BAR ======
      const drawShapBar = (feat, yPos, maxWidth) => {
        const barHeight = 4;
        const isPositive = (feat.contribution ?? 0) >= 0;
        const absContrib = Math.abs(feat.contribution ?? feat.importance * (result.synergy_score - 4.25));
        const barW = Math.min(maxWidth * 0.6, Math.max(3, (absContrib / Math.max(Math.abs(result.synergy_score), 1)) * maxWidth * 0.5));

        // Feature label
        doc.setFontSize(7);
        doc.setFont('helvetica', 'normal');
        setColor(colors.textMuted);
        const displayName = feat.feature.length > 45 ? feat.feature.substring(0, 45) + '...' : feat.feature;
        doc.text(displayName, margin + 4, yPos + 3);

        // Bar
        const barX = margin + 4;
        const barY = yPos + 5;
        setFill(isPositive ? colors.primary : colors.danger);
        doc.roundedRect(barX, barY, barW, barHeight, 1, 1, 'F');

        // Value label
        doc.setFontSize(6.5);
        doc.setFont('helvetica', 'bold');
        setColor(isPositive ? colors.primary : colors.danger);
        const contribStr = `${isPositive ? '+' : ''}${(feat.contribution ?? 0).toFixed(2)}`;
        doc.text(contribStr, barX + barW + 3, barY + 3.5);

        // Importance %
        doc.setFontSize(6);
        setColor(colors.textDim);
        doc.text(`(${(feat.importance * 100).toFixed(0)}%)`, pageWidth - margin - 4, barY + 3.5, { align: 'right' });

        return yPos + 13;
      };

      // ═══════════════════════════════════════════
      //   PAGE 1 — Executive Summary
      // ═══════════════════════════════════════════
      fillPageBg();
      y = drawHeader();

      // 1A: Executive Summary Section
      y = drawSection('EXECUTIVE SUMMARY', '■', y);

      y = drawDataRow('Drug A (Primary Agent):', result.drug_a, y);
      y = drawDataRow('Drug B (Secondary Agent):', result.drug_b, y);
      y = drawDataRow('Target Cell Line:', result.cell_line, y);
      y = drawDataRow('Cancer Type / Lineage:', result.cancer_type || 'Multi-lineage', y);
      y = drawDataRow('Inference Model:', result.model_used?.toUpperCase() || 'XGBOOST', y);
      y = drawDataRow('Report Generated:', new Date().toLocaleString('en-US', { dateStyle: 'full', timeStyle: 'short' }), y);

      y += 4;

      // 1B: Key Metrics Cards
      const cardW = (contentWidth - 6) / 3;

      const scoreColor = result.synergy_score > 10 ? colors.primary :
        result.synergy_score < -10 ? colors.danger : colors.warning;
      drawCard(margin, y, cardW, 20, 'BLISS SYNERGY SCORE',
        `${result.synergy_score > 0 ? '+' : ''}${result.synergy_score.toFixed(2)}`, scoreColor);

      drawCard(margin + cardW + 3, y, cardW, 20, 'MODEL CONFIDENCE',
        `${(result.confidence * 100).toFixed(0)}%`, colors.secondary);

      const classColor = result.synergy_class === 'synergistic' ? colors.primary :
        result.synergy_class === 'antagonistic' ? colors.danger : colors.warning;
      drawCard(margin + (cardW + 3) * 2, y, cardW, 20, 'RESPONSE CLASS',
        result.synergy_class.toUpperCase(), classColor);

      y += 26;

      // 1C: Clinical Classification
      y = drawSection('CLINICAL CLASSIFICATION & INTERPRETATION', '■', y);

      doc.setFontSize(7.5);
      doc.setFont('helvetica', 'normal');
      setColor(colors.text);

      let classification = '';
      if (result.synergy_score > 10) {
        classification = `The combination of ${result.drug_a} and ${result.drug_b} demonstrates SYNERGISTIC activity ` +
          `(Bliss Independence Score: ${result.synergy_score.toFixed(2)} > 10.0) when evaluated against ${result.cell_line} ` +
          `(${result.cancer_type || 'oncology'} lineage). This suggests enhanced therapeutic efficacy beyond additive expectations, ` +
          `indicating potential for combination chemotherapy regimen development.`;
      } else if (result.synergy_score < -10) {
        classification = `The combination of ${result.drug_a} and ${result.drug_b} exhibits ANTAGONISTIC interaction ` +
          `(Bliss Independence Score: ${result.synergy_score.toFixed(2)} < -10.0) on ${result.cell_line}. ` +
          `This counter-productive interaction suggests mutual interference between the agents' mechanisms of action, ` +
          `contraindicated for combination therapy development.`;
      } else {
        classification = `The combination of ${result.drug_a} and ${result.drug_b} shows ADDITIVE/NEUTRAL response ` +
          `(Bliss Independence Score: ${result.synergy_score.toFixed(2)}, within -10 to +10 range) on ${result.cell_line}. ` +
          `No significant synergistic enhancement or antagonistic interference detected.`;
      }

      const splitLines = doc.splitTextToSize(classification, contentWidth - 8);
      doc.text(splitLines, margin + 4, y + 1);
      y += splitLines.length * 4 + 4;

      // 1D: 95% Confidence Interval
      if (result.ci_lower != null && result.ci_upper != null) {
        y += 2;
        y = drawSection('STATISTICAL CONFIDENCE (95% CI)', '■', y);
        y = drawDataRow('Point Estimate (ŷ):', `${result.synergy_score.toFixed(2)} Bliss`, y, colors.primary);
        y = drawDataRow('95% CI Lower Bound:', `${result.ci_lower.toFixed(2)} Bliss`, y);
        y = drawDataRow('95% CI Upper Bound:', `${result.ci_upper.toFixed(2)} Bliss`, y);
        y = drawDataRow('Interval Width:', `${(result.ci_upper - result.ci_lower).toFixed(2)} Bliss units`, y);
        y = drawDataRow('Key Biomarker:', result.key_biomarker || 'N/A', y, colors.accent);
      }

      // 1E: Multi-model comparison
      if (result.all_predictions) {
        y += 4;
        y = drawSection('MULTI-MODEL CROSS-VALIDATION', '■', y);
        y = drawDataRow('XGBoost (Primary):', `${result.all_predictions.xgboost} Bliss`, y, colors.primary);
        y = drawDataRow('Random Forest:', `${result.all_predictions.random_forest} Bliss`, y, colors.secondary);
        y = drawDataRow('Ridge Regression:', `${result.all_predictions.ridge} Bliss`, y);
        y = drawDataRow('Ensemble Mean:', `${result.all_predictions.ensemble} Bliss`, y, colors.accent);
      }

      drawFooter(1, 2);

      // ═══════════════════════════════════════════
      //   PAGE 2 — SHAP Feature Attribution & Molecular Intelligence
      // ═══════════════════════════════════════════
      doc.addPage();
      fillPageBg();

      // Minimal header bar for subsequent pages
      setFill(colors.primary);
      doc.rect(0, 0, pageWidth, 3, 'F');
      setFill(colors.cardBg);
      doc.roundedRect(margin, 6, contentWidth, 10, 2, 2, 'F');
      doc.setFontSize(8);
      doc.setFont('helvetica', 'bold');
      setColor(colors.primary);
      doc.text('CANCER DRUG COMBINATION PLATFORM — Feature Attribution & Molecular Intelligence', margin + 4, 13);

      y = 22;

      // 2A: SHAP Feature Attribution
      y = drawSection('SHAP FEATURE ATTRIBUTION (EXPLAINABLE AI)', '■', y);

      doc.setFontSize(7);
      doc.setFont('helvetica', 'normal');
      setColor(colors.textMuted);
      doc.text('Population Baseline E[Y] = 4.25 Bliss (DrugComb 391K average)', margin + 4, y + 1);
      y += 6;

      if (result.shap_features && result.shap_features.length > 0) {
        // Column headers
        doc.setFontSize(6.5);
        doc.setFont('helvetica', 'bold');
        setColor(colors.textDim);
        doc.text('FEATURE', margin + 4, y + 1);
        doc.text('CONTRIBUTION', margin + 4 + contentWidth * 0.35, y + 1);
        doc.text('IMPORTANCE', pageWidth - margin - 4, y + 1, { align: 'right' });

        setDraw(colors.border);
        doc.setLineWidth(0.2);
        y += 3;
        doc.line(margin + 4, y, pageWidth - margin - 4, y);
        y += 3;

        for (const feat of result.shap_features) {
          y = drawShapBar(feat, y, contentWidth);
        }

        // Total
        doc.setLineWidth(0.3);
        setDraw(colors.primary);
        doc.line(margin + 4, y, pageWidth - margin - 4, y);
        y += 4;

        doc.setFontSize(8);
        doc.setFont('helvetica', 'bold');
        setColor(colors.primary);
        doc.text(`TOTAL PREDICTED: ${result.synergy_score > 0 ? '+' : ''}${result.synergy_score.toFixed(2)} Bliss`, margin + 4, y);
        y += 8;
      }

      // 2B: Molecular Pharmacology Summary
      y = drawSection('MOLECULAR PHARMACOLOGY OVERVIEW', '■', y);

      const molA = molecularData?.drug_a;
      const molB = molecularData?.drug_b;

      if (molA) {
        y = drawDataRow(`${molA.name} — Drug Class:`, molA.drug_class, y, colors.primary);
        y = drawDataRow(`${molA.name} — Formula:`, molA.chemical_formula, y);
        y = drawDataRow(`${molA.name} — MW:`, `${molA.molecular_weight} g/mol`, y);
        y = drawDataRow(`${molA.name} — Targets:`, (molA.targets || []).join(', '), y, colors.accent);
        doc.setFontSize(7);
        doc.setFont('helvetica', 'normal');
        setColor(colors.textMuted);
        const moaLines = doc.splitTextToSize(`MoA: ${molA.moa}`, contentWidth - 8);
        doc.text(moaLines, margin + 4, y);
        y += moaLines.length * 3.5 + 3;
      }

      if (molB) {
        y += 2;
        y = drawDataRow(`${molB.name} — Drug Class:`, molB.drug_class, y, colors.secondary);
        y = drawDataRow(`${molB.name} — Formula:`, molB.chemical_formula, y);
        y = drawDataRow(`${molB.name} — MW:`, `${molB.molecular_weight} g/mol`, y);
        y = drawDataRow(`${molB.name} — Targets:`, (molB.targets || []).join(', '), y, colors.accent);
        doc.setFontSize(7);
        doc.setFont('helvetica', 'normal');
        setColor(colors.textMuted);
        const moaLines = doc.splitTextToSize(`MoA: ${molB.moa}`, contentWidth - 8);
        doc.text(moaLines, margin + 4, y);
        y += moaLines.length * 3.5 + 3;
      }

      // 2C: Synergy Pathway Rationale
      const pathway = molecularData?.pathway_analysis;
      if (pathway) {
        y += 2;
        y = drawSection('SYNERGY PATHWAY RATIONALE', '■', y);
        doc.setFontSize(7.5);
        doc.setFont('helvetica', 'normal');
        setColor(colors.text);
        const pathLines = doc.splitTextToSize(pathway.rationale || '', contentWidth - 8);
        doc.text(pathLines, margin + 4, y);
        y += pathLines.length * 3.5 + 3;

        if (pathway.clinical_evidence) {
          doc.setFontSize(7);
          setColor(colors.accent);
          doc.text(`Clinical Evidence: ${pathway.clinical_evidence}`, margin + 4, y);
          y += 5;
        }
      }

      // 2D: Disclaimer
      y = Math.max(y + 4, pageHeight - 45);
      setFill([30, 41, 59]);
      doc.roundedRect(margin, y, contentWidth, 22, 2, 2, 'F');
      setDraw(colors.border);
      doc.roundedRect(margin, y, contentWidth, 22, 2, 2, 'S');

      doc.setFontSize(7);
      doc.setFont('helvetica', 'bold');
      setColor(colors.warning);
      doc.text('⚠ RESEARCH DISCLAIMER', margin + 4, y + 5);

      doc.setFontSize(6.5);
      doc.setFont('helvetica', 'normal');
      setColor(colors.textMuted);
      const disclaimer = 'This computational analysis is generated by the Cancer Drug Combination Prediction & Research Platform ' +
        'for in-silico research prioritization only. Results should be validated through in-vitro wet-lab ' +
        'dose-response assays before any translational or clinical consideration. This report does not constitute ' +
        'medical advice, clinical diagnosis, or treatment recommendation.';
      const discLines = doc.splitTextToSize(disclaimer, contentWidth - 8);
      doc.text(discLines, margin + 4, y + 10);

      drawFooter(2, 2);

      // ====== SAVE ======
      const filename = `Cancer_Drug_Prediction_${result.drug_a}_${result.drug_b}_${result.cell_line}_${new Date().toISOString().split('T')[0]}.pdf`;
      doc.save(filename);

      setGenerated(true);
      toast.success('Clinical dossier exported successfully!', { id: 'pdf-gen' });
      setTimeout(() => setGenerated(false), 4000);
    } catch (err) {
      console.error('PDF generation failed:', err);
      toast.error('Failed to generate PDF. Please try again.', { id: 'pdf-gen' });
    } finally {
      setGenerating(false);
    }
  };

  return (
    <div className="relative group">
      <button
        onClick={generatePDF}
        disabled={generating}
        className={`relative flex items-center gap-2.5 px-5 py-3 rounded-xl text-sm font-bold transition-all duration-300 overflow-hidden ${
          generated
            ? 'bg-teal-500/20 border border-teal-500/40 text-teal-300'
            : generating
            ? 'bg-slate-800 border border-slate-700 text-slate-400 cursor-wait'
            : 'bg-gradient-to-r from-rose-600 via-rose-500 to-pink-600 hover:from-rose-500 hover:to-pink-500 text-white shadow-lg shadow-rose-500/25 hover:shadow-rose-500/40 hover:scale-[1.02] active:scale-[0.98]'
        }`}
      >
        {/* Shimmer effect on idle */}
        {!generating && !generated && (
          <div className="absolute inset-0 overflow-hidden">
            <div className="absolute -left-full top-0 bottom-0 w-full bg-gradient-to-r from-transparent via-white/10 to-transparent"
              style={{ animation: 'shimmer 3s ease-in-out infinite' }} />
          </div>
        )}

        <div className="relative z-10 flex items-center gap-2.5">
          {generating ? (
            <>
              <FaSpinner className="animate-spin text-base" />
              <span>Generating Dossier...</span>
            </>
          ) : generated ? (
            <>
              <FaCheckCircle className="text-teal-400 text-base" />
              <span>Dossier Exported!</span>
            </>
          ) : (
            <>
              <FaFilePdf className="text-base" />
              <span>Export Clinical Dossier</span>
              <FaDownload className="text-xs opacity-80" />
            </>
          )}
        </div>
      </button>

      {/* Tooltip description */}
      <div className="absolute left-0 -bottom-11 w-64 opacity-0 group-hover:opacity-100 transition-opacity duration-200 pointer-events-none z-50">
        <div className="px-3 py-1.5 rounded-lg bg-slate-900 border border-slate-700 text-[10px] text-slate-400 shadow-lg">
          Generate a multi-page A4 clinical research PDF with SHAP analysis, molecular data, and statistical confidence intervals.
        </div>
      </div>
    </div>
  );
}
